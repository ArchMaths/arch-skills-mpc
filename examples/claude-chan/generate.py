# ---------------- helpers ----------------
sc.comment("Helpers. fw places a local shape (p,q,r) in a frame: origin o, axes (i,j,k) given per coordinate.")
sc.func('fw(p,q,r,o,i,j,k)', 'o+p*i+q*j+r*k')
sc.comment("Capsule profile: u runs 0..pi from one end to the other, radius r0 -> r1, rounded ends.")
sc.func('cf(u)', '(1-cos(u))/2')
sc.func('cr(u,r0,r1)', '(r0+(r1-r0)*cf(u))*sqrt(sqrt(1-cos(u)^4))')


def place(L, o, fr):
    a, b, c = fr
    return tuple(f"fw({L[0]},{L[1]},{L[2]},{fmt(o[i])},{fmt(a[i])},{fmt(b[i])},{fmt(c[i])})" for i in range(3))


def capsule(A, B, r0, r1, color, ref, q=1.0, up=(0, 0, 1)):
    d = sub(B, A)
    a, b, c = frame(d, up)
    L = (f"cr(u,{fmt(r0)},{fmt(r1)})*cos(w)", f"{fmt(q)}*cr(u,{fmt(r0)},{fmt(r1)})*sin(w)", f"{fmt(norm(d))}*cf(u)")
    sc.surface(place(L, A, (a, b, c)), ('u', 0, 'pi'), ('w', 0, '2*pi'), color, ref, ('tube', 'u'))


def ellipsoid(C, R, color, ref, fr=None, orient='closed', urange=(0, 'pi'), opacity=None):
    L = (f"{fmt(R[0])}*sin(u)*cos(v)", f"{fmt(R[1])}*sin(u)*sin(v)", f"{fmt(R[2])}*cos(u)")
    if fr is None:
        xyz = tuple(f"{fmt(C[i])}+{L[i]}" for i in range(3))
    else:
        xyz = place(L, C, fr)
    sc.surface(xyz, ('u', urange[0], urange[1]), ('v', 0, '2*pi'), color, ref, orient, opacity=opacity)


