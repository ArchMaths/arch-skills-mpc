sc_flower_defined = False


def flower_funcs():
    global sc_flower_defined
    if sc_flower_defined:
        return
    sc_flower_defined = True
    sc.comment("""Chrysanthemum: petal layers fa/fb/fc in local coordinates (r 0..1 out from the centre, w around),
n petals of length R, cupped upward by cu, turned by ro; a ridge runs along each petal.""")
    sc.func('fpr(w,n,ro)', 'abs(cos(n*(w-ro)/2))^0.7')
    sc.func('fa(r,w,n,sz,ro)', 'sz*r*(0.28+0.72*fpr(w,n,ro))*cos(w)')
    sc.func('fb(r,w,n,sz,ro)', 'sz*r*(0.28+0.72*fpr(w,n,ro))*sin(w)')
    sc.func('fc(r,w,n,sz,cu,ro)', 'sz*(cu*r^2+0.07*r*fpr(w,n,ro)^3)')


def flower(C, n_dir, R, ref, up=(0, 0, 1), colors=(ORANGE, ORANGE_LT, AMBER, GOLD), layers=3, flat=False):
    """3D chrysanthemum centred at C facing n_dir."""
    flower_funcs()
    fr = frame(n_dir, up)
    specs = [(16, 1.0, 0.18, 0.0), (14, 0.74, 0.34, 0.11), (12, 0.48, 0.55, 0.05)][:layers]
    for li, (n, s, cu, ro) in enumerate(specs):
        Cl = add(C, mul(fr[2], 0.04 * li * R))
        cu_ = 0.03 if flat else cu
        L = (f"fa(r,w,{n},{fmt(R * s)},{fmt(ro)})", f"fb(r,w,{n},{fmt(R * s)},{fmt(ro)})", f"fc(r,w,{n},{fmt(R * s)},{fmt(cu_)},{fmt(ro)})")
        sc.surface(place(L, Cl, fr), ('r', 0, 1), ('w', 0, '2*pi'), colors[li], f'{ref}P{li + 1}', ('dir', fr[2]))
    Cc = add(C, mul(fr[2], (0.1 if not flat else 0.03) * R))
    L = (f"{fmt(0.22 * R)}*sin(u)*cos(v)", f"{fmt(0.22 * R)}*sin(u)*sin(v)", f"{fmt(0.12 * R)}*cos(u)*(1+0.15*cos(12*v)*sin(u))")
    sc.surface(place(L, Cc, fr), ('u', 0, 'pi'), ('v', 0, '2*pi'), colors[3], f'{ref}Mid', 'closed')
    return fr


def bow_funcs():
    if 'bl(' in ''.join(sc.out[:50]) or 'bowdone' in sc.ns:
        return
    sc.ns['bowdone'] = True
    sc.comment("""Bow loop in local coordinates: s 0..1 from the knot outward, w around; length le, half-height he,
half-thickness te. The loop is pinched at the knot and rounded at the end.""")
    sc.func('bla(s,le)', 'le*s')
    sc.func('blh(s,w,he)', 'he*sin(pi*s)^0.55*(0.35+0.65*s)*cos(w)')
    sc.func('blt(s,w,te)', 'te*sin(pi*s)^0.5*sin(w)')


def bow(C, fr, size, ref, color=BLACK, rim=GOLD, loops=((1, 0.25), (-1, -0.25)), knot=True):
    """fr = (a: loop axis, b: loop height axis, c: facing). loops: (direction sign, tilt)."""
    bow_funcs()
    a, b, c = fr
    le, he, te = size
    for k, (sg, tilt) in enumerate(loops):
        ax = unit(add(mul(a, sg * math.cos(tilt)), mul(b, math.sin(tilt))))
        bx = cross(c, ax)
        L = (f"bla(s,{fmt(le)})", f"blh(s,w,{fmt(he)})", f"blt(s,w,{fmt(te)})")
        sc.surface(place(L, C, (ax, bx, c)), ('s', 0, 1), ('w', 0, '2*pi'), color, f'{ref}Loop{k + 1}', ('tube', 'u'))
        if rim:
            L = (f"bla(s,{fmt(le * 1.07)})", f"blh(s,w,{fmt(he * 1.12)})", f"blt(s,w,{fmt(te * 0.45)})")
            sc.surface(place(L, add(C, mul(ax, -0.01)), (ax, bx, c)), ('s', 0, 1), ('w', 0, '2*pi'), rim, f'{ref}Rim{k + 1}', ('tube', 'u'))
    if knot:
        ellipsoid(add(C, mul(c, te * 0.3)), (he * 0.42, he * 0.5, te * 1.15), color, f'{ref}Knot', fr=fr)


def ribbon(pts, width, color, ref, facing, twist=0.0, vcut=0.18, rim=None):
    """Flat ribbon along a Bezier centre line; q across the width; V-cut end."""
    cx_, cy_, cz_ = bezier_poly(pts)
    # width direction: perpendicular to the centre line within the plane facing `facing`
    d = unit(sub(pts[-1], pts[0]))
    wdir = unit(cross(facing, d))
    s_expr = f"s*(1-{fmt(vcut)}*(1-abs(q)))"
    def comp(i, wscale):
        return f"{horner([cx_, cy_, cz_][i], s_expr)}+{fmt(width * wscale * wdir[i])}*q"
    xyz = tuple(comp(i, 1) for i in range(3))
    sc.surface(xyz, ('s', 0, 1), ('q', -1, 1), color, ref, ('dir', facing))
    if rim:
        off = mul(unit(facing), -0.006)
        xyz = tuple(f"{comp(i, 1.18)}+{fmt(off[i])}" for i in range(3))
        sc.surface(xyz, ('s', 0, 1), ('q', -1, 1), rim, ref + 'Rim', ('dir', facing))


def tassel(top, length, color, ref, r=0.05, knob=GOLD):
    """Cord top -> knob -> tassel cone with fine threads, hanging straight down."""
    x, y, z = top
    capsule((x, y, z), (x, y, z - 0.25 * length), 0.008, 0.008, knob, ref + 'Cord')
    zk = z - 0.25 * length
    ellipsoid((x, y, zk - 0.04), (r * 0.75, r * 0.75, r * 0.85), knob, ref + 'Knob')
    zt = zk - 0.09
    L = length * 0.7
    X = f"{fmt(x)}+({fmt(r * 0.45)}+{fmt(r * 0.6)}*s^0.6)*(1+0.06*abs(sin(14*w)))*cos(w)"
    Y = f"{fmt(y)}+({fmt(r * 0.45)}+{fmt(r * 0.6)}*s^0.6)*(1+0.06*abs(sin(14*w)))*sin(w)"
    Z = f"{fmt(zt)}-{fmt(L)}*s*(1-0.06*abs(sin(7*w+1)))"
    sc.surface((X, Y, Z), ('s', 0, 1), ('w', 0, '2*pi'), color, ref, ('tube', 'u'))
    ellipsoid((x, y, zt - 0.02), (r * 0.62, r * 0.62, 0.03), knob, ref + 'Band')


